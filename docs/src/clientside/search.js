/**
 * Docs search, backed by the static index Pagefind writes at build time into
 * /docs/pagefind/. That bundle only exists in a built site (`bun run build`),
 * so in `bun dev` search silently no-ops instead of throwing.
 */

const RESULT_LIMIT = 20;

/** @typedef {{ url: string, meta: { title?: string }, excerpt: string }} PagefindResultData */
/** @typedef {{ init: () => Promise<void>, debouncedSearch: (term: string) => Promise<{ results: { data: () => Promise<PagefindResultData> }[] } | null> }} Pagefind */

/** @type {Pagefind | null | undefined} undefined = not yet attempted */
let pagefind;

/** @returns {Promise<Pagefind | null>} */
async function loadPagefind() {
  if (pagefind !== undefined) return pagefind;
  try {
    // @ts-expect-error -- only present in the built site, generated by the pagefind CLI
    pagefind = await import("/docs/pagefind/pagefind.js");
    await pagefind.init();
  } catch {
    pagefind = null;
  }
  return pagefind;
}

/**
 * @param {string} text
 * @returns {string}
 */
function escapeHtml(text) {
  return text.replace(
    /[&<>"']/g,
    (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[ch] ?? ch,
  );
}

/**
 * @param {HTMLElement} target
 * @returns {boolean}
 */
function isTyping(target) {
  return (
    target instanceof HTMLElement &&
    (target.tagName === "INPUT" || target.tagName === "TEXTAREA" || target.isContentEditable)
  );
}

function init() {
  const dialog = document.getElementById("search-dialog");
  const input = document.getElementById("search-input");
  const results = document.getElementById("search-results");
  if (!(dialog instanceof HTMLElement) || !(input instanceof HTMLInputElement) || !results) return;

  async function runSearch(term) {
    if (!term.trim()) {
      results.innerHTML = "";
      return;
    }

    const pf = await loadPagefind();

    if (!pf) {
      results.innerHTML =
        '<p class="fs-s ink-subtle px-xs py-s">Search is unavailable in this preview.</p>';
      return;
    }

    const search = await pf.debouncedSearch(term);
    if (!search) return; // superseded by a newer keystroke

    const entries = await Promise.all(
      search.results.slice(0, RESULT_LIMIT).map((result) => result.data()),
    );

    if (entries.length === 0) {
      results.innerHTML = `<p class="fs-s ink-subtle px-xs py-s">No results for "${escapeHtml(term)}".</p>`;
      return;
    }

    results.innerHTML = entries
      .map(
        (entry) => `
          <a href="${entry.url}" class="d-block px-xs py-2xs br-m bg-wash:hover">
            <div class="fs-s fw-medium">${escapeHtml(entry.meta?.title ?? entry.url)}</div>
            <div class="fs-s ink-subtle lh-snug">${entry.excerpt}</div>
          </a>
        `,
      )
      .join("");
  }

  input.addEventListener("input", () => {
    void runSearch(input.value);
  });

  dialog.addEventListener("toggle", (event) => {
    if (/** @type {ToggleEvent} */ (event).newState === "open") {
      input.value = "";
      results.innerHTML = "";
      input.focus();
      void loadPagefind();
    }
  });

  document.addEventListener("keydown", (event) => {
    const shortcut =
      (event.key === "k" && (event.metaKey || event.ctrlKey)) ||
      (event.key === "/" && !isTyping(/** @type {HTMLElement} */ (event.target)));
    if (!shortcut) return;
    event.preventDefault();
    dialog.showPopover();
  });
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", init);
} else {
  init();
}
