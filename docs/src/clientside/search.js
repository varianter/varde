/**
 * Docs search, backed by the static index Pagefind writes at build time into
 * /docs/pagefind/. That bundle only exists in a built site (`bun run build`),
 * so in `bun dev` search silently no-ops instead of throwing.
 */

const RESULT_LIMIT = 20;

/** @typedef {{ url: string, meta: { title?: string }, excerpt: string }} PagefindResultData */
/** @typedef {{ init: () => Promise<void>, debouncedSearch: (term: string) => Promise<{ results: { data: () => Promise<PagefindResultData> }[] } | null> }} Pagefind */

/** @type {Pagefind | null | undefined} undefined = not yet attempted */
let pagefind;

/** @returns {Promise<Pagefind | null>} */
async function loadPagefind() {
  if (pagefind !== undefined) return pagefind;
  try {
    // @ts-expect-error -- only present in the built site, generated by the pagefind CLI
    pagefind = await import("/docs/pagefind/pagefind.js");
    await pagefind.init();
  } catch {
    pagefind = null;
  }
  return pagefind;
}

/**
 * @param {string} text
 * @returns {string}
 */
function escapeHtml(text) {
  return text.replace(
    /[&<>"']/g,
    (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[ch] ?? ch,
  );
}

/**
 * @param {HTMLElement} target
 * @returns {boolean}
 */
function isTyping(target) {
  return (
    target instanceof HTMLElement &&
    (target.tagName === "INPUT" || target.tagName === "TEXTAREA" || target.isContentEditable)
  );
}

function init() {
  const dialog = document.getElementById("search-dialog");
  const input = document.getElementById("search-input");
  const results = document.getElementById("search-results");
  if (!(dialog instanceof HTMLElement) || !(input instanceof HTMLInputElement) || !results) return;

  const emptyState = results.querySelector("#search-empty");

  function clearResults() {
    results.innerHTML = "";
    if (emptyState) results.append(emptyState);
  }

  async function runSearch(term) {
    if (!term.trim()) {
      clearResults();
      return;
    }

    const pf = await loadPagefind();

    if (!pf) {
      results.innerHTML =
        '<p class="fs-s ink-subtle px-xs py-s">Search is unavailable in this preview.</p>';
      return;
    }

    const search = await pf.debouncedSearch(term);
    if (!search) return; // superseded by a newer keystroke

    const entries = await Promise.all(
      search.results.slice(0, RESULT_LIMIT).map((result) => result.data()),
    );

    if (entries.length === 0) {
      results.innerHTML = `<p class="fs-s ink-subtle px-xs py-s ta-center">AAaah, bugger! No results for <strong>"${escapeHtml(term)}"</strong>.</p>`;
      return;
    }

    results.innerHTML = entries
      .map(
        (entry) => `
          <a href="${entry.url}" class="d-block px-xs py-2xs br-m bg-wash:hover">
            <div class="fs-s fw-medium">${escapeHtml(entry.meta?.title ?? entry.url)}</div>
            <div class="fs-s ink-subtle lh-snug">${entry.excerpt}</div>
          </a>
        `,
      )
      .join("");
  }

  input.addEventListener("input", () => {
    void runSearch(input.value);
  });

  dialog.addEventListener("toggle", (event) => {
    if (/** @type {ToggleEvent} */ (event).newState === "open") {
      input.value = "";
      clearResults();
      input.focus();
      void loadPagefind();
    }
  });

  document.addEventListener("keydown", (event) => {
    const shortcut =
      (event.key === "k" && (event.metaKey || event.ctrlKey)) ||
      (event.key === "/" && !isTyping(/** @type {HTMLElement} */ (event.target)));
    if (!shortcut) return;
    event.preventDefault();
    dialog.showPopover();
  });
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", init);
} else {
  init();
}

// <combo-keys> — layers arrow-key navigation over an input and a list.
// No shadow DOM. Knows nothing about the search. Only looks at the DOM.
//
// <combo-keys>
//   <input />
//   <div class="results"><a href="…">…</a></div>
// </combo-keys>
//
// Optional: <combo-keys items="li > a"> to override what counts as an item.

class ComboKeys extends HTMLElement {
  #last = null; // last focused element inside, for the removal check
  #observer = null;

  connectedCallback() {
    this.addEventListener("keydown", this);
    this.addEventListener("focusin", this);

    // Focused item removed (e.g. async results replaced the list).
    // Browsers don't fire blur/focusout on removal, so we watch the DOM.
    this.#observer = new MutationObserver(() => {
      if (this.#last && !this.#last.isConnected) this.#focusInput();
    });
    this.#observer.observe(this, { childList: true, subtree: true });
  }

  disconnectedCallback() {
    this.removeEventListener("keydown", this);
    this.removeEventListener("focusin", this);
    this.#observer?.disconnect();
  }

  handleEvent(e) {
    if (e.type === "focusin") {
      this.#last = e.target;
      return;
    }

    const input = this.#input;
    if (!input) return;

    const items = this.#items;
    const t = e.target;
    const i = items.indexOf(t);
    const onItem = i !== -1;

    switch (e.key) {
      case "ArrowDown":
        e.preventDefault();
        if (t === input) this.#focusItem(items[0]);
        else if (onItem) this.#focusItem(items[i + 1]); // last item: does nothing
        break;
      case "ArrowUp":
        e.preventDefault();
        if (i === 0) this.#focusInput();
        else if (onItem) this.#focusItem(items[i - 1]);
        break;
      case "Home":
        if (onItem) {
          e.preventDefault();
          this.#focusItem(items[0]);
        }
        break;
      case "End":
        if (onItem) {
          e.preventDefault();
          this.#focusItem(items.at(-1));
        }
        break;
      default:
        // Typing while on an item: hand the keystroke back to the input.
        // Focusing during keydown means the character still lands there.
        if (onItem && this.#isTyping(e)) this.#focusInput();
    }
  }

  get #input() {
    return this.querySelector("input, textarea");
  }

  get #items() {
    const sel = this.getAttribute("items") ?? "a, button, [role=option]";
    // Drop items that can't take focus. el.focus() fails silently on
    // hidden, disabled, or inert elements, so without this filter an
    // arrow press would appear to do nothing and the user would get stuck.
    return [...this.querySelectorAll(sel)].filter(
      (el) => el.checkVisibility() && !el.disabled && !el.closest("[inert]"),
    );
  }

  #isTyping(e) {
    if (e.ctrlKey || e.metaKey || e.altKey) return false;
    return e.key.length === 1 || e.key === "Backspace";
  }

  #focusItem(el) {
    if (!el) return;
    el.focus();
    el.scrollIntoView({ block: "center" });
  }

  #focusInput() {
    const input = this.#input;
    if (!input) return;
    input.focus();
    const end = input.value.length;
    input.setSelectionRange?.(end, end);
  }
}

customElements.define("combo-keys", ComboKeys);
